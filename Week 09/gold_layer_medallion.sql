-- ===========================================================
-- DIM CUSTOMER
-- Grain: 1 row per customer_id PER VERSION
-- Type: SCD Type 2 — history preserved
--
-- Sourced from silver.customer_profile, the wide Silver view
-- that already folds the primary address and primary phone
-- onto the customer row.
--
-- The load closes the current row (effective_to =
-- CURRENT_TIMESTAMP, is_current = FALSE) when any tracked
-- attribute changes, then inserts a new version. There is
-- deliberately NO unique constraint on customer_id — several
-- versions of one customer are the point of Type 2.
-- ===========================================================

CREATE TABLE IF NOT EXISTS gold.dim_customer
(
    customer_key BIGINT GENERATED ALWAYS AS IDENTITY,

    customer_id BIGINT NOT NULL,

    customer_no VARCHAR(50),
    nic_number VARCHAR(20),
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    dob DATE,
    gender VARCHAR(20),
    occupation VARCHAR(100),
    email VARCHAR(255),

    primary_address_line1 VARCHAR(255),
    primary_address_line2 VARCHAR(255),
    primary_city VARCHAR(100),
    primary_state VARCHAR(100),
    primary_postal_code VARCHAR(20),

    primary_phone_number VARCHAR(30),
    primary_phone_type VARCHAR(20),

    effective_from TIMESTAMP NOT NULL,
    effective_to TIMESTAMP NOT NULL,
    is_current BOOLEAN NOT NULL,

    created_at TIMESTAMP,
    updated_at TIMESTAMP,

    source_system VARCHAR(50),

    PRIMARY KEY (customer_key)
);


