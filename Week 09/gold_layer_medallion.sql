-- ===========================================================
-- INDEXES
--
-- Every Type 2 load looks the current version up by
-- (business key, is_current) — once in the UPDATE that closes
-- the old row, once in the LEFT JOIN that decides whether a
-- new version is needed. These partial indexes keep that
-- lookup cheap as history accumulates.
-- ===========================================================

CREATE INDEX IF NOT EXISTS idx_dim_customer_current
    ON gold.dim_customer (customer_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_dim_account_current
    ON gold.dim_account (account_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_dim_card_current
    ON gold.dim_card (card_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_dim_loan_current
    ON gold.dim_loan (loan_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS idx_dim_employee_current
    ON gold.dim_employee (employee_id)
    WHERE is_current;
