-- ===========================================================
-- GOLD LAYER
--
-- The presentation layer of the Medallion architecture:
-- Bronze (raw landing) -> Silver (cleaned & conformed) -> Gold.
--
-- Run this AFTER bronze_layer_medallion.sql and
-- silver_layer_medallion.sql from Week 08, and BEFORE running
-- the Week 09 Airflow DAGs:
--
--   03_load_gold_dimensions.py  -> loads the 9 dimensions below
--   04_load_gold_facts.py       -> loads the fact tables
--
-- Every dimension carries a surrogate key (BIGINT IDENTITY)
-- separate from its business key. Facts join on the surrogate
-- key, which is what lets a Type 2 dimension keep several
-- versions of the same business entity without the fact rows
-- becoming ambiguous.
-- ===========================================================

CREATE SCHEMA IF NOT EXISTS gold;


-- ===========================================================
-- DIM DATE
-- Grain: 1 row per calendar day
-- Type: generated (not sourced from Silver)
--
-- date_key is a smart key in YYYYMMDD form, generated by the
-- DAG with TO_CHAR(d, 'YYYYMMDD')::INTEGER. It is declared as
-- the primary key because the load relies on
-- ON CONFLICT (date_key) DO NOTHING to stay idempotent.
-- ===========================================================

CREATE TABLE IF NOT EXISTS gold.dim_date
(
    date_key INTEGER NOT NULL,

    full_date DATE NOT NULL,

    day_of_month INTEGER,
    day_of_week INTEGER,
    day_name VARCHAR(20),

    week_of_year INTEGER,

    month_number INTEGER,
    month_name VARCHAR(20),

    quarter_number INTEGER,
    year_number INTEGER,

    is_weekend BOOLEAN,

    PRIMARY KEY (date_key)
);


-- ===========================================================
-- DIM BRANCH
-- Grain: 1 row per branch_id (current state only)
-- Type: SCD Type 1 — attributes are overwritten in place
--
-- branch_id is UNIQUE because the load upserts with
-- ON CONFLICT (branch_id) DO UPDATE.
-- ===========================================================

CREATE TABLE IF NOT EXISTS gold.dim_branch
(
    branch_key BIGINT GENERATED ALWAYS AS IDENTITY,

    branch_id BIGINT NOT NULL,

    branch_code VARCHAR(20),
    name VARCHAR(255),
    address VARCHAR(500),
    ifsc_code VARCHAR(20),

    created_at TIMESTAMP,
    updated_at TIMESTAMP,

    source_system VARCHAR(50),

    PRIMARY KEY (branch_key),
    UNIQUE (branch_id)
);


